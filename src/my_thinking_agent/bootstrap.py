"""Initialize and connect a private knowledge root on one local device."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import tomllib
from typing import Iterable, Mapping

from .learning_sources import (
    LEARNING_SOURCES_ENV,
    LearningSourceError,
    learning_sources_json,
    parse_learning_source_names,
    parse_learning_source_specs,
    parse_learning_sources,
)


class BootstrapError(ValueError):
    """Raised when a bootstrap operation would overwrite or expose local data."""


GENERATED_CONFIG_HEADER = "# Generated by my_thinking_agent.bootstrap. Do not commit this file."
MCP_ENABLED_TOOLS = (
    "list_principles",
    "search_decisions",
    "read_decision",
    "create_decision",
    "update_decision",
    "delete_decision",
    "list_archived_decisions",
    "restore_decision",
    "list_learning_sources",
    "search_learning_sources",
    "read_learning_source",
    "prepare_conversation_learning",
    "save_conversation_learning",
)


def _project_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _private_template_root() -> Path:
    return _project_root() / "templates" / "my-thinking-agent-private"


def _copy_private_template(destination: Path) -> None:
    """Copy the public, data-free private-repository template into an empty root."""
    template_root = _private_template_root()
    required = ("decision-principles.md", "decisions/README.md", "AGENTS.md")
    if not all((template_root / relative).is_file() for relative in required):
        raise BootstrapError("private repository template is incomplete")
    for source in sorted(template_root.rglob("*")):
        if not source.is_file():
            continue
        relative = source.relative_to(template_root)
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source.read_text(encoding="utf-8"), encoding="utf-8")


def _toml_string(value: str | Path) -> str:
    """JSON strings are valid TOML basic strings for the values we emit."""
    return json.dumps(str(value), ensure_ascii=False)


def initialize_knowledge_root(knowledge_root: Path) -> Path:
    """Create a minimal private-root layout without overwriting existing data."""
    root = knowledge_root.expanduser().resolve()
    root.mkdir(parents=True, exist_ok=True)
    unexpected = [
        entry.name for entry in root.iterdir() if entry.name not in {".git", ".jj"}
    ]
    if unexpected:
        names = ", ".join(sorted(unexpected))
        raise BootstrapError(
            f"knowledge root is not empty; refusing to overwrite: {names}"
        )

    _copy_private_template(root)
    return root


def validate_knowledge_root(knowledge_root: Path) -> Path:
    """Require the minimum layout before Codex receives a local path."""
    root = knowledge_root.expanduser().resolve()
    missing: list[str] = []
    if not (root / "decision-principles.md").is_file():
        missing.append("decision-principles.md")
    if not (root / "decisions").is_dir():
        missing.append("decisions/")
    if missing:
        raise BootstrapError(f"knowledge root is incomplete: {', '.join(missing)}")
    return root


def render_project_config(
    project_root: Path,
    knowledge_root: Path,
    learning_sources: Mapping[str, Path] | None = None,
) -> str:
    """Render the local-only configuration for the stdio MCP server."""
    source_environment = ""
    if learning_sources:
        source_environment = (
            f"{LEARNING_SOURCES_ENV} = "
            f"{_toml_string(learning_sources_json(learning_sources))}\n"
        )
    enabled_tools = ", ".join(json.dumps(tool) for tool in MCP_ENABLED_TOOLS)
    return f"""{GENERATED_CONFIG_HEADER}
# It holds this device's private knowledge-root path.

[mcp_servers.personal_knowledge]
command = \"uv\"
args = [\"run\", \"--directory\", {_toml_string(project_root)}, \"personal-knowledge-mcp\"]
enabled_tools = [{enabled_tools}]
default_tools_approval_mode = \"approve\"
startup_timeout_sec = 10
tool_timeout_sec = 30

[mcp_servers.personal_knowledge.env]
MY_THINKING_AGENT_KNOWLEDGE_ROOT = {_toml_string(knowledge_root)}
{source_environment}"""


def _learning_sources_from_config(config_text: str) -> dict[str, Path]:
    """Preserve opted-in source roots when refreshing a generated config."""
    try:
        parsed = tomllib.loads(config_text)
        environment = parsed["mcp_servers"]["personal_knowledge"].get("env", {})
    except (tomllib.TOMLDecodeError, KeyError, TypeError) as exc:
        raise BootstrapError("generated MCP configuration cannot be parsed safely") from exc
    configured = environment.get(LEARNING_SOURCES_ENV)
    if configured is None:
        return {}
    if not isinstance(configured, str):
        raise BootstrapError(f"{LEARNING_SOURCES_ENV} must be a TOML string")
    try:
        return parse_learning_sources(configured)
    except LearningSourceError as exc:
        raise BootstrapError(str(exc)) from exc


def _generated_config_text(project_root: Path) -> str:
    """Read only a bootstrap-generated local configuration."""
    target = project_root / ".codex" / "config.toml"
    if not target.is_file():
        raise BootstrapError(
            f"{target} is unavailable; supply --knowledge-root for initial configuration"
        )
    config_text = target.read_text(encoding="utf-8")
    if not config_text.startswith(GENERATED_CONFIG_HEADER):
        raise BootstrapError(
            f"{target} is hand-authored; it will not be read or overwritten automatically"
        )
    return config_text


def _configured_knowledge_root(project_root: Path) -> Path:
    """Recover the local private-root path from a generated local configuration."""
    config_text = _generated_config_text(project_root)
    try:
        parsed = tomllib.loads(config_text)
        environment = parsed["mcp_servers"]["personal_knowledge"]["env"]
        configured = environment["MY_THINKING_AGENT_KNOWLEDGE_ROOT"]
    except (tomllib.TOMLDecodeError, KeyError, TypeError) as exc:
        raise BootstrapError("generated MCP configuration cannot be parsed safely") from exc
    if not isinstance(configured, str) or not configured.strip():
        raise BootstrapError("generated MCP configuration has no private knowledge-root path")
    return validate_knowledge_root(Path(configured))


def configured_learning_sources(project_root: Path) -> list[dict[str, str | bool]]:
    """Report configured local sources without reading their file contents."""
    sources = _learning_sources_from_config(_generated_config_text(project_root))
    return [
        {"name": name, "path": str(path), "available": path.is_dir()}
        for name, path in sorted(sources.items())
    ]


def write_project_config(
    project_root: Path,
    knowledge_root: Path,
    *,
    update_generated: bool = False,
    learning_sources: Mapping[str, Path] | None = None,
    remove_learning_sources: Iterable[str] = (),
    replace_learning_sources: bool = False,
) -> Path:
    """Write local config without overwriting user-authored configuration."""
    project = project_root.expanduser().resolve()
    knowledge = validate_knowledge_root(knowledge_root)
    target = project / ".codex" / "config.toml"
    existing_sources: dict[str, Path] = {}
    if target.exists():
        existing = target.read_text(encoding="utf-8")
        if not update_generated or not existing.startswith(GENERATED_CONFIG_HEADER):
            raise BootstrapError(
                f"{target} already exists; refusing to overwrite local Codex configuration"
            )
        existing_sources = _learning_sources_from_config(existing)
    if replace_learning_sources:
        configured_sources = dict(learning_sources or {})
    else:
        configured_sources = {**existing_sources, **(learning_sources or {})}
    for name in remove_learning_sources:
        if name not in configured_sources:
            raise BootstrapError(f"learning source is not configured: {name}")
        del configured_sources[name]
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        render_project_config(project, knowledge, configured_sources), encoding="utf-8"
    )
    return target


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Initialize a private knowledge root or connect it to this local Codex project."
    )
    parser.add_argument(
        "--knowledge-root",
        type=Path,
        help=(
            "Private local directory or private repository checkout holding decision data. "
            "Required for initial setup; generated local config supplies it for updates."
        ),
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=_project_root(),
        help="my-thinking-agent checkout to configure (defaults to this checkout).",
    )
    parser.add_argument(
        "--initialize-knowledge-root",
        action="store_true",
        help="Create the private-root template only when the target is empty.",
    )
    parser.add_argument(
        "--write-project-config",
        action="store_true",
        help="Create .codex/config.toml without overwriting an existing local config.",
    )
    parser.add_argument(
        "--update-project-config",
        action="store_true",
        help="Update only a configuration previously generated by this bootstrap command.",
    )
    parser.add_argument(
        "--print-project-config",
        action="store_true",
        help="Print the local configuration instead of writing it.",
    )
    parser.add_argument(
        "--learning-source",
        action="append",
        metavar="NAME=PATH",
        help=(
            "Add or update one local source root for conversation learning; repeat for "
            "multiple roots. Relative paths are resolved from --project-root."
        ),
    )
    parser.add_argument(
        "--remove-learning-source",
        action="append",
        metavar="NAME",
        help="Remove one named local source root from a generated configuration.",
    )
    parser.add_argument(
        "--replace-learning-sources",
        action="store_true",
        help="Replace all configured source roots with the supplied --learning-source values.",
    )
    parser.add_argument(
        "--list-learning-sources",
        action="store_true",
        help="List configured local source roots and whether each is currently available.",
    )
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    if not (
        args.initialize_knowledge_root
        or args.write_project_config
        or args.update_project_config
        or args.print_project_config
        or args.list_learning_sources
    ):
        parser.error("choose at least one operation")

    try:
        project = args.project_root.expanduser().resolve()
        learning_sources = parse_learning_source_specs(
            args.learning_source, base_path=project
        )
        remove_learning_sources = parse_learning_source_names(args.remove_learning_source)
        if args.replace_learning_sources and learning_sources is None:
            raise BootstrapError(
                "--replace-learning-sources requires at least one --learning-source"
            )
        if args.list_learning_sources:
            for source in configured_learning_sources(project):
                status = "available" if source["available"] else "unavailable"
                print(f"{source['name']}: {source['path']} ({status})")
            return
        if args.knowledge_root is None:
            if args.initialize_knowledge_root or args.write_project_config or args.print_project_config:
                parser.error("--knowledge-root is required for initial configuration")
            root = _configured_knowledge_root(project)
        else:
            root = (
                initialize_knowledge_root(args.knowledge_root)
                if args.initialize_knowledge_root
                else validate_knowledge_root(args.knowledge_root)
            )
        if args.print_project_config:
            print(
                render_project_config(
                    project, root, learning_sources
                )
            )
        if args.write_project_config:
            path = write_project_config(
                project,
                root,
                learning_sources=learning_sources,
                remove_learning_sources=remove_learning_sources,
                replace_learning_sources=args.replace_learning_sources,
            )
            print(f"Created local Codex configuration: {path}")
        if args.update_project_config:
            path = write_project_config(
                project,
                root,
                update_generated=True,
                learning_sources=learning_sources,
                remove_learning_sources=remove_learning_sources,
                replace_learning_sources=args.replace_learning_sources,
            )
            print(f"Updated generated local Codex configuration: {path}")
        if args.initialize_knowledge_root:
            print(f"Initialized private knowledge root: {root}")
    except (BootstrapError, LearningSourceError) as exc:
        parser.exit(2, f"error: {exc}\n")


if __name__ == "__main__":
    main()
