"""Initialize and connect a private knowledge root on one local device."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


class BootstrapError(ValueError):
    """Raised when a bootstrap operation would overwrite or expose local data."""


PRINCIPLES_TEMPLATE = """# 判断原則

このfileには複数の課題に共通する、簡潔で一般化した判断ruleを記載します。
password、private key、生の会話、顧客名、第三者の個人情報は置かないでください。

## 根拠と不確実性

- 確認済みの事実、仮定、推奨を分ける。
- 推奨を変え得る未確認事項を示す。

## 判断の質

- 不可逆な操作の前に、可逆でreview可能な手順を優先する。
- 選択肢、trade-off、推奨理由を示す。

## 権限とprivacy

- 外部への送信、公開、支出、契約、削除、credential変更には明示的な承認を求める。
- 出力する個人情報と第三者情報を最小限にする。
"""

DECISIONS_README = """# 判断記録

各事例をMarkdown fileとして保存します。公開repositoryではなく、このprivate knowledge rootだけに置いてください。

必須front matter:

```md
---
id: short-stable-id
title: 機微情報を含まない短いtitle
date: YYYY-MM-DD
classification: internal
tags: comma, separated, terms
---
```

`classification` には `public`、`internal`、`confidential` のいずれかを指定します。通常のMCP serverは `internal` までしか返しません。
"""

GENERATED_CONFIG_HEADER = "# Generated by my_thinking_agent.bootstrap. Do not commit this file."


def _project_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _toml_string(value: str | Path) -> str:
    """JSON strings are valid TOML basic strings for the values we emit."""
    return json.dumps(str(value), ensure_ascii=False)


def initialize_knowledge_root(knowledge_root: Path) -> Path:
    """Create a minimal private-root layout without overwriting existing data."""
    root = knowledge_root.expanduser().resolve()
    root.mkdir(parents=True, exist_ok=True)
    unexpected = [
        entry.name for entry in root.iterdir() if entry.name not in {".git", ".jj"}
    ]
    if unexpected:
        names = ", ".join(sorted(unexpected))
        raise BootstrapError(
            f"knowledge root is not empty; refusing to overwrite: {names}"
        )

    decisions = root / "decisions"
    decisions.mkdir()
    (root / "decision-principles.md").write_text(PRINCIPLES_TEMPLATE, encoding="utf-8")
    (decisions / "README.md").write_text(DECISIONS_README, encoding="utf-8")
    return root


def validate_knowledge_root(knowledge_root: Path) -> Path:
    """Require the minimum layout before Codex receives a local path."""
    root = knowledge_root.expanduser().resolve()
    missing: list[str] = []
    if not (root / "decision-principles.md").is_file():
        missing.append("decision-principles.md")
    if not (root / "decisions").is_dir():
        missing.append("decisions/")
    if missing:
        raise BootstrapError(f"knowledge root is incomplete: {', '.join(missing)}")
    return root


def render_project_config(project_root: Path, knowledge_root: Path) -> str:
    """Render the local-only configuration for the read-only stdio MCP server."""
    return f"""{GENERATED_CONFIG_HEADER}
# It holds this device's private knowledge-root path.

[mcp_servers.personal_knowledge]
command = \"uv\"
args = [\"run\", \"--directory\", {_toml_string(project_root)}, \"personal-knowledge-mcp\"]
enabled_tools = [\"list_principles\", \"search_decisions\", \"read_decision\", \"create_decision\", \"update_decision\", \"delete_decision\", \"list_archived_decisions\", \"restore_decision\"]
default_tools_approval_mode = \"approve\"
startup_timeout_sec = 10
tool_timeout_sec = 30

[mcp_servers.personal_knowledge.env]
MY_THINKING_AGENT_KNOWLEDGE_ROOT = {_toml_string(knowledge_root)}
"""


def write_project_config(
    project_root: Path, knowledge_root: Path, *, update_generated: bool = False
) -> Path:
    """Write local config without overwriting user-authored configuration."""
    project = project_root.expanduser().resolve()
    knowledge = validate_knowledge_root(knowledge_root)
    target = project / ".codex" / "config.toml"
    if target.exists():
        existing = target.read_text(encoding="utf-8")
        if not update_generated or not existing.startswith(GENERATED_CONFIG_HEADER):
            raise BootstrapError(
                f"{target} already exists; refusing to overwrite local Codex configuration"
            )
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_project_config(project, knowledge), encoding="utf-8")
    return target


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Initialize a private knowledge root or connect it to this local Codex project."
    )
    parser.add_argument(
        "--knowledge-root",
        type=Path,
        required=True,
        help="Private local directory or private repository checkout holding decision data.",
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=_project_root(),
        help="my-thinking-agent checkout to configure (defaults to this checkout).",
    )
    parser.add_argument(
        "--initialize-knowledge-root",
        action="store_true",
        help="Create the private-root template only when the target is empty.",
    )
    parser.add_argument(
        "--write-project-config",
        action="store_true",
        help="Create .codex/config.toml without overwriting an existing local config.",
    )
    parser.add_argument(
        "--update-project-config",
        action="store_true",
        help="Update only a configuration previously generated by this bootstrap command.",
    )
    parser.add_argument(
        "--print-project-config",
        action="store_true",
        help="Print the local configuration instead of writing it.",
    )
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    if not (
        args.initialize_knowledge_root
        or args.write_project_config
        or args.update_project_config
        or args.print_project_config
    ):
        parser.error("choose at least one operation")

    try:
        root = (
            initialize_knowledge_root(args.knowledge_root)
            if args.initialize_knowledge_root
            else validate_knowledge_root(args.knowledge_root)
        )
        if args.print_project_config:
            print(render_project_config(args.project_root.expanduser().resolve(), root))
        if args.write_project_config:
            path = write_project_config(args.project_root, root)
            print(f"Created local Codex configuration: {path}")
        if args.update_project_config:
            path = write_project_config(args.project_root, root, update_generated=True)
            print(f"Updated generated local Codex configuration: {path}")
        if args.initialize_knowledge_root:
            print(f"Initialized private knowledge root: {root}")
    except BootstrapError as exc:
        parser.exit(2, f"error: {exc}\n")


if __name__ == "__main__":
    main()
